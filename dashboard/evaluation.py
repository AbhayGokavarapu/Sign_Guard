"""Page 5 — Evaluation (displays actual benchmark results)."""
from __future__ import annotations
import json, os, time
import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
from dashboard.components import inject_css, page_header, section_header, empty_state
import config

EVAL_JSON = os.path.join(config.BENCHMARKS_DIR, "evaluation_results.json")
EVAL_CSV  = os.path.join(config.BENCHMARKS_DIR, "evaluation_results.csv")
CLS_JSON  = os.path.join(config.BENCHMARKS_DIR, "classification_metrics.json")
TAMP_JSON = os.path.join(config.BENCHMARKS_DIR, "tampering_metrics.json")
LOC_JSON  = os.path.join(config.BENCHMARKS_DIR, "localization_metrics.json")


def render() -> None:
    page_header("Evaluation", "Measured benchmark results from the labeled synthetic dataset.")

    st.warning(
        "**These metrics are computed on a synthetic dataset generated by this codebase.** "
        "They confirm functional correctness on the designed test cases. "
        "They do NOT establish real-world generalisation performance."
    )

    # ── Run / load controls ────────────────────────────────────────────────
    col_run, col_info = st.columns([1, 2])
    with col_run:
        if st.button("▶  Re-run Evaluation"):
            with st.spinner("Generating dataset and running full pipeline on every fixture…"):
                import subprocess, sys
                ret = subprocess.run(
                    [sys.executable,
                     os.path.join(config.BASE_DIR, "benchmarks", "run_evaluation.py")],
                    capture_output=True, text=True, timeout=600,
                    cwd=config.BASE_DIR,
                )
                if ret.returncode == 0:
                    st.success("Evaluation complete.")
                else:
                    st.error(f"Evaluation script failed. Check console output.")
    with col_info:
        st.caption(
            "Re-running regenerates the 30-fixture dataset and re-executes the "
            "full pipeline on each. Takes ~15–60 s depending on hardware."
        )

    # ── Load results ──────────────────────────────────────────────────────
    data = None
    if "eval_data" not in st.session_state and os.path.exists(EVAL_JSON):
        with open(EVAL_JSON) as f:
            st.session_state["eval_data"] = json.load(f)
    data = st.session_state.get("eval_data")

    if data is None:
        empty_state("No benchmark results found. Click 'Re-run Evaluation' above.", "📊")
        return

    # ── Section A: Classification ──────────────────────────────────────────
    cls_data = None
    if os.path.exists(CLS_JSON):
        with open(CLS_JSON) as f:
            cls_data = json.load(f)

    section_header("Task A — Document Classification", "🏷️")
    if cls_data:
        ca1, ca2, ca3 = st.columns(3)
        ca1.metric("Total files",  cls_data["total"])
        ca2.metric("Correct",       cls_data["correct"])
        ca3.metric("Accuracy",     f"{cls_data['accuracy']:.1%}")
        st.caption(cls_data.get("note", ""))

    # ── Section B: Tampering alert ────────────────────────────────────────
    section_header("Task B — Tampering-Alert Detection", "🚨")
    st.caption(
        "Positive = ground-truth label involves tampering or shadow. "
        "Predicted positive = verdict of TAMPERING DETECTED or REVIEW REQUIRED."
    )
    t1, t2, t3, t4, t5 = st.columns(5)
    t1.metric("Accuracy",  f"{data['accuracy']:.1%}")
    t2.metric("Precision", f"{data['precision']:.1%}")
    t3.metric("Recall",    f"{data['recall']:.1%}")
    t4.metric("F1-Score",  f"{data['f1']:.1%}")
    t5.metric("Unsupported", data.get("unsupported", 0))

    n1, n2, n3, n4 = st.columns(4)
    n1.metric("TP", data["TP"])
    n2.metric("FP", data["FP"])
    n3.metric("FN", data["FN"])
    n4.metric("TN", data["TN"])

    # Confusion matrix
    cm = [[data["TP"], data["FN"]], [data["FP"], data["TN"]]]
    fig_cm = go.Figure(go.Heatmap(
        z=cm,
        x=["Predicted +", "Predicted −"],
        y=["Actual +", "Actual −"],
        text=cm, texttemplate="%{text}",
        colorscale=[[0,"#EFF6FF"],[1,"#1D4ED8"]],
        showscale=False,
    ))
    fig_cm.update_layout(height=280, margin=dict(l=10,r=10,t=30,b=10),
                         paper_bgcolor="#FFFFFF", plot_bgcolor="#F8FAFC")
    st.plotly_chart(fig_cm)

    if data["FP"] > 0:
        st.info(
            f"**{data['FP']} false positives** — the conservative design raises "
            "REVIEW REQUIRED rather than missing potential tampering. "
            "This trades precision for recall (recall = 100%)."
        )
    if data["FN"] > 0:
        st.error(f"**{data['FN']} false negatives** — positive cases were missed.")

    # ── Section C: Localisation ────────────────────────────────────────────
    section_header("Task C — Signature Localisation", "✍️")
    loc_data = None
    if os.path.exists(LOC_JSON):
        with open(LOC_JSON) as f:
            loc_data = json.load(f)
    if loc_data:
        l1, l2, l3 = st.columns(3)
        l1.metric("Documents with sigs", loc_data["sig_documents"])
        l2.metric("At least one candidate found", loc_data["at_least_one_found"])
        l3.metric("Detection rate", f"{loc_data['detection_rate']:.1%}")
        st.caption(loc_data.get("note", ""))

    # ── Per-file table ─────────────────────────────────────────────────────
    section_header("Per-File Results", "📋")
    records = data.get("records", [])
    if records:
        df = pd.DataFrame(records)
        def _correct(r):
            if r["label"].replace("_"," ").upper() in ("TAMPERING DETECTED","REVIEW REQUIRED"):
                return "✓" if r["pred"].upper() in ("TAMPERING DETECTED","REVIEW REQUIRED") else "✗"
            return "✓" if r["pred"].upper() not in ("TAMPERING DETECTED","REVIEW REQUIRED") else "✗"
        if "correct" not in df.columns:
            df["correct"] = df.apply(_correct, axis=1)
        st.dataframe(df[["file","category","label","pred","elapsed","correct"]], height=380)

        # Distribution
        section_header("Dataset Distribution", "📦")
        dist = df["category"].value_counts().reset_index()
        dist.columns = ["Category", "Count"]
        fig_dist = px.bar(dist, x="Category", y="Count",
                          color_discrete_sequence=px.colors.qualitative.Set2)
        fig_dist.update_layout(height=250, showlegend=False,
                               plot_bgcolor="#F8FAFC", paper_bgcolor="#FFFFFF")
        st.plotly_chart(fig_dist)

        # Runtime
        section_header("Runtime Performance", "⏱️")
        fig_time = px.histogram(df, x="elapsed", nbins=20,
                                color_discrete_sequence=["#2563EB"])
        fig_time.update_layout(height=230, plot_bgcolor="#F8FAFC",
                               paper_bgcolor="#FFFFFF",
                               xaxis_title="Time (s)", yaxis_title="Files")
        st.plotly_chart(fig_time)
        rt1, rt2, rt3, rt4 = st.columns(4)
        rt1.metric("Total",   f"{data['total_time_s']:.1f} s")
        rt2.metric("Mean",    f"{df['elapsed'].mean():.3f} s")
        rt3.metric("Median",  f"{df['elapsed'].median():.3f} s")
        rt4.metric("Max",     f"{df['elapsed'].max():.3f} s")

    # ── Downloads ─────────────────────────────────────────────────────────
    section_header("Downloads", "📥")
    d1, d2 = st.columns(2)
    if os.path.exists(EVAL_JSON):
        with open(EVAL_JSON, "rb") as f:
            d1.download_button("⬇ evaluation_results.json", f.read(),
                               "evaluation_results.json", "application/json")
    if os.path.exists(EVAL_CSV):
        with open(EVAL_CSV, "rb") as f:
            d2.download_button("⬇ evaluation_results.csv", f.read(),
                               "evaluation_results.csv", "text/csv")
